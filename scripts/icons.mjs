// scripts/icons.mjs — extract the Tabler outline icons Curve uses into src/app/icons.ts.
// Usage: node scripts/icons.mjs [path-to-tabler-icons]  (default: ../tabler-icons)
// Tabler Icons are MIT licensed: https://github.com/tabler/tabler-icons
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(process.argv[2] ?? process.env.TABLER_DIR ?? '../tabler-icons', 'icons/outline');

/** Curve icon name -> Tabler outline icon name. */
const ICONS = {
  new: 'file-plus', open: 'folder-open', save: 'device-floppy', undo: 'arrow-back-up', redo: 'arrow-forward-up',
  delete: 'trash', 'zoom-in': 'zoom-in', 'zoom-out': 'zoom-out', fit: 'arrows-maximize', code: 'code', help: 'help',
  keyboard: 'keyboard', magnet: 'magnet', grid: 'grid-dots', 'to-path': 'vector-bezier', ellipse: 'oval',
  select: 'pointer', direct: 'vector', rect: 'square', circle: 'circle', line: 'line', polygon: 'pentagon', star: 'star',
  pen: 'vector-bezier-2', pencil: 'pencil', text: 'typography', image: 'photo', layers: 'stack-2',
  eye: 'eye', 'eye-off': 'eye-off', lock: 'lock', unlock: 'lock-open', copy: 'copy', paste: 'clipboard', cut: 'scissors',
  download: 'download', upload: 'upload', chevron: 'chevron-down', more: 'dots', close: 'x', palette: 'palette',
  'align-left': 'layout-align-left', 'align-center': 'layout-align-center', 'align-right': 'layout-align-right',
  'align-top': 'layout-align-top', 'align-middle': 'layout-align-middle', 'align-bottom': 'layout-align-bottom',
  'distribute-h': 'layout-distribute-vertical', 'distribute-v': 'layout-distribute-horizontal',
  'flip-h': 'flip-vertical', 'flip-v': 'flip-horizontal', 'to-front': 'stack-front', 'to-back': 'stack-back',
  forward: 'stack-forward', backward: 'stack-backward', group: 'box-multiple', ungroup: 'box-multiple-0',
  command: 'command', eyedropper: 'color-picker', sun: 'sun', moon: 'moon', settings: 'adjustments', duplicate: 'copy-plus',
  symbol: 'components', gradient: 'color-swatch', pattern: 'texture', marker: 'arrow-narrow-right', mask: 'mask',
  filter: 'blur', style: 'brush', 'go-to': 'square-rounded-arrow-right', definitions: 'stack-2',
};

const out = ['// Generated by scripts/icons.mjs from Tabler Icons (MIT). Do not edit by hand.', '', 'export const ICONS = {'];
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(root, `${file}.svg`), 'utf8');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .split('\n').map((l) => l.trim()).filter(Boolean).join('');
  out.push(`  ${JSON.stringify(name)}: ${JSON.stringify(body)},`);
}
out.push('} as const;', '', 'export type IconName = keyof typeof ICONS;', '');
writeFileSync('src/app/icons.ts', out.join('\n'));
console.log(`Wrote ${Object.keys(ICONS).length} icons`);
